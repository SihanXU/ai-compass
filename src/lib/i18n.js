const BASE = (import.meta.env.BASE_URL || '/').replace(/\/?$/, '/');
/** url('en', 'wiki/x') → /ai-compass/en/wiki/x/ */
export function url(lang, p = '') {
  const tail = p ? `${p.replace(/^\/|\/$/g, '')}/` : '';
  return `${BASE}${lang}/${tail}`.replace(/\/\?/, '?');
}
export const asset = (p) => `${BASE}${p.replace(/^\//, '')}`;

