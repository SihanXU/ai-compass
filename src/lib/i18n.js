export function t(lang, key, vars) {
  const v = S[key];
  if (!v) throw new Error(`missing string ${key}`);
  let s = lang === 'zh' ? v[1] : v[0];
  if (vars) for (const [k, x] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, x);
  return s;
}
/** the strings a client script needs, in one language */
export const pack = (lang, keys) => Object.fromEntries(keys.map((k) => [k, t(lang, k)]));
